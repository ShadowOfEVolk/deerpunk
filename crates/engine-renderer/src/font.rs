/// Битмап-шрифт 6×8, ASCII 32..=126. Каждый символ — байт на строку, левый бит = MSB.
/// Глифы рисуются на GPU как квады из font-atlas (белые, tint-ятся цветом текста).

use crate::snapshot::{Instance, RenderSnapshot, TexSel};

pub const GLYPH_W: f32 = 8.0;
pub const GLYPH_H: f32 = 8.0;

/// Число глифов в атласе (ASCII 32..=126).
pub const CHAR_COUNT: usize = 95;
pub const FIRST_CHAR: u8 = b' ';

/// Ширина font-atlas в пикселях (по одному глифу в ряд).
pub const ATLAS_W: u32 = 760;
pub const ATLAS_H: u32 = 8;

pub fn glyph_index(byte: u8) -> Option<usize> {
    if byte < FIRST_CHAR || byte > b'~' {
        return None;
    }
    Some((byte - FIRST_CHAR) as usize)
}

/// UV-прямоугольник глифа в font-atlas.
pub fn glyph_uv(byte: u8) -> Option<[f32; 4]> {
    let idx = glyph_index(byte)?;
    let u0 = idx as f32 / CHAR_COUNT as f32;
    let u1 = (idx + 1) as f32 / CHAR_COUNT as f32;
    Some([u0, 0.0, u1, 1.0])
}

/// Ширина текста в пикселях при заданном масштабе.
pub fn text_width_f32(text: &str, scale: f32) -> f32 {
    text.bytes()
        .filter_map(glyph_index)
        .count() as f32
        * GLYPH_W
        * scale
}

/// Квад одного глифа в снапшот.
pub fn push_char(snap: &mut RenderSnapshot, x: f32, y: f32, byte: u8, color: [f32; 4], scale: f32) {
    let Some(uv) = glyph_uv(byte) else { return };
    snap.push_hud(Instance::font(
        x + GLYPH_W * scale * 0.5,
        y + GLYPH_H * scale * 0.5,
        GLYPH_W * scale * 0.5,
        GLYPH_H * scale * 0.5,
        uv,
        color,
    ));
}

/// Строка текста в снапшот.
pub fn push_text(
    snap: &mut RenderSnapshot,
    mut x: f32,
    y: f32,
    text: &str,
    color: [f32; 4],
    scale: f32,
) {
    for byte in text.bytes() {
        if glyph_index(byte).is_none() {
            x += GLYPH_W * scale;
            continue;
        }
        push_char(snap, x, y, byte, color, scale);
        x += GLYPH_W * scale;
    }
}

/// Строка текста по центру.
pub fn push_text_centered(
    snap: &mut RenderSnapshot,
    cx: f32,
    y: f32,
    text: &str,
    color: [f32; 4],
    scale: f32,
) {
    let w = text_width_f32(text, scale);
    push_text(snap, cx - w * 0.5, y, text, color, scale);
}

/// Текст с чёрной тенью (offset +1px).
pub fn push_text_shadow(
    snap: &mut RenderSnapshot,
    x: f32,
    y: f32,
    text: &str,
    color: [f32; 4],
    scale: f32,
) {
    let shadow = [0.0, 0.0, 0.0, 200.0 / 255.0];
    push_text(snap, x + 1.0, y + 1.0, text, shadow, scale);
    push_text(snap, x, y, text, color, scale);
}

/// Центрированный текст с тенью.
pub fn push_text_centered_shadow(
    snap: &mut RenderSnapshot,
    cx: f32,
    y: f32,
    text: &str,
    color: [f32; 4],
    scale: f32,
) {
    let w = text_width_f32(text, scale);
    push_text_shadow(snap, cx - w * 0.5, y, text, color, scale);
}

/// RGBA-байты font-atlas (премультипленный белый) для загрузки в GPU-текстуру.
pub fn build_font_atlas() -> Vec<u8> {
    let mut data = vec![0u8; (ATLAS_W * ATLAS_H * 4) as usize];
    for (idx, glyph) in FONT.iter().enumerate() {
        for row in 0..8 {
            let bits = glyph[row];
            for col in 0..6 {
                if bits & (0x80 >> col) == 0 {
                    continue;
                }
                let px = (idx as u32 * 8 + col as u32) as usize;
                let offset = (row as usize * ATLAS_W as usize + px) * 4;
                data[offset..offset + 4].copy_from_slice(&[255, 255, 255, 255]);
            }
        }
    }
    data
}

